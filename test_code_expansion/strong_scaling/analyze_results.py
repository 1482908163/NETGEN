@contextmanager
def run_guard(directory):
    """Share the runner's lock so analysis never cleans an active run."""
    lock = directory/".run.lock"
    fd = os.open(lock, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, "w") as handle:
        try:
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            yield False
        else:
            try:
                yield True
            finally:
                fcntl.flock(handle, fcntl.LOCK_UN)

def compress_result(path):
    """Atomic, lossless compression; keep the source if anything fails."""
    target = path.with_name(path.name + ".gz")
    if not path.is_file() or path.is_symlink() or target.is_symlink():
        return 0
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".compress-", delete=False) as out:
            temporary = Path(out.name)
            with path.open("rb") as source, gzip.GzipFile(filename="", mode="wb", fileobj=out, mtime=0) as packed:
                shutil.copyfileobj(source, packed, 1024 * 1024)
        saved = path.stat().st_size - temporary.stat().st_size
        if saved <= 0:
            return 0
        os.replace(temporary, target)
        path.unlink()
        return saved
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)

